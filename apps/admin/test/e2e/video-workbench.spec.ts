test('保存契约：409 保留、保存锁定、成功刷新影像基线', async ({ page }) => {
  const api = await startStudio(page)
  await navigate(page, 'video')
  api.conflict = true
  await page.getByTestId('video-title-en').fill('Saved video')
  await page.getByTestId('snapshot-save').click()
  await expect(page.getByTestId('toast-viewport')).toContainText('req_c4464811-558f-4491-b698-2404d74f0167')
  expect((await snapshot(page)).videos[0]!.title.en).toBe('Saved video')
  await page.getByTestId('video-title-en').fill('Retry video')
  api.conflict = false
  api.hold = true
  await page.getByTestId('snapshot-save').click()
  for (const id of ['video-title-zh', 'video-add', 'version-clone', 'studio-tools']) await expect(page.getByTestId(id)).toBeDisabled()
  await expect.poll(() => Boolean(api.finish)).toBe(true)
  api.finish!()
  await expect(page.getByTestId('video-title-en')).toHaveValue('Retry video')
  await expect(page.getByTestId('video-title-en')).toBeEnabled()
  await expect(page.locator('.studio-meta')).toContainText('Saved')
})
