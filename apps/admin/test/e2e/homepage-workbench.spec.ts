import { expect, test } from '@playwright/test'
import fixture from '../../../../content/fixtures/homepage.json' with { type: 'json' }
import { apply, navigate, roundTrip, snapshot, startStudio } from './studio'

test('新增宣传位与板块编排，导出再导入保持内容', async ({ page }) => {
  await startStudio(page)
  await navigate(page, 'homepage')
  await page.getByTestId('homepage-hero-add').click()
  await page.getByTestId('homepage-headline-zh').fill('新专辑宣传')
  await page.getByTestId('homepage-headline-en').fill('New release')
  await page.getByTestId('homepage-hero-asset').selectOption('asset_hero_studio')
  await page.getByTestId('homepage-starts-at').fill('2026-08-28T00:00:00Z')
  await page.getByTestId('homepage-ends-at').fill('2026-09-01T00:00:00Z')
  const section = page.getByTestId('homepage-section-section_hero')
  const id = (await page.getByTestId('homepage-hero-id').textContent())!.trim()
  await section.getByTestId('homepage-item-add-select').selectOption(id)
  await section.getByTestId('homepage-item-add').click()
  await section.getByTestId('homepage-item-up').last().click()
  await apply(page)
  await expect(page.getByTestId('homepage-error')).toHaveCount(0)
  const value = await snapshot(page)
  expect(value.heroSlides.at(-1)).toMatchObject({ headline: { 'zh-CN': '新专辑宣传', en: 'New release' }, startsAt: '2026-08-28T00:00:00Z' })
  expect(value.homepage.sections[0]!.itemIds).toEqual(['hero_studio', 'hero_stage', id, 'hero_release'])
  expect(value.releases).toEqual(fixture.releases)
  await roundTrip(page, value)
})

test('离开保护保留输入，隐藏目标校验失败不覆盖快照', async ({ page }) => {
  const api = await startStudio(page)
  await navigate(page, 'homepage')
  await page.getByTestId('homepage-headline-zh').fill('未保存首页')
  await expect(page.getByTestId('studio-tools')).toBeDisabled()
  await navigate(page, 'music')
  await expect(page.getByTestId('leave-dialog')).toBeVisible()
  await page.getByTestId('leave-keep').click()
  await expect(page.getByTestId('homepage-headline-zh')).toHaveValue('未保存首页')
  const section = page.getByTestId('homepage-section-section_music')
  await section.getByTestId('homepage-section-enabled').uncheck()
  await page.getByTestId('snapshot-save').click()
  const targetIndex = fixture.heroSlides.findIndex(hero => hero.target?.kind === 'internal' && hero.target.contentId === 'release_01')
  expect(targetIndex).toBeGreaterThanOrEqual(0)
  await expect(page.getByTestId('toast-viewport')).toContainText(`/heroSlides/${targetIndex}/target/contentId`)
  await expect(page.getByTestId('homepage-target-content')).toBeFocused()
  await expect(page.getByTestId('homepage-target-content')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByTestId('homepage-error')).toHaveCount(0)
  expect(api.saves).toHaveLength(0)
  await section.getByTestId('homepage-section-enabled').check()
  await navigate(page, 'music')
  await page.getByTestId('leave-save').click()
  await expect(page.getByTestId('music-workbench')).toBeVisible()
  expect(api.saves[0]!.heroSlides[0]!.headline['zh-CN']).toBe('未保存首页')
  await expect(page.getByTestId('homepage-headline-zh')).toHaveCount(0)
})

test('保存期间锁定首页，修订冲突保留内容且成功重建基线', async ({ page }) => {
  const api = await startStudio(page)
  await navigate(page, 'homepage')
  api.conflict = true
  await page.getByTestId('homepage-headline-en').fill('Saved headline')
  await page.getByTestId('snapshot-save').click()
  await expect(page.getByTestId('toast-viewport')).toContainText('req_browser')
  expect((await snapshot(page)).heroSlides[0]!.headline.en).toBe('Saved headline')
  api.conflict = false
  api.hold = true
  await page.getByTestId('snapshot-save').click()
  await expect(page.getByTestId('homepage-headline-zh')).toBeDisabled()
  await expect(page.getByTestId('homepage-hero-add')).toBeDisabled()
  await expect(page.getByTestId('studio-tools')).toBeDisabled()
  await expect.poll(() => Boolean(api.finish)).toBe(true)
  api.finish!()
  await expect(page.getByTestId('homepage-headline-en')).toHaveValue('Saved headline')
  await expect(page.getByTestId('homepage-headline-zh')).toBeEnabled()
  await expect(page.locator('.studio-meta')).toContainText('Saved')
  await page.getByTestId('homepage-headline-en').fill('Next edit')
  await expect(page.getByTestId('studio-tools')).toBeDisabled()
})
