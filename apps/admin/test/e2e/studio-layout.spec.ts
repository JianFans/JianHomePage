import { expect, test } from '@playwright/test'
import { backend, navigate, selectVersion, startStudio } from './studio'

test('长表单滚动后仍能保存预览，键盘聚焦不被顶栏遮挡', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await startStudio(page)
  await navigate(page, 'video')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Videos')
  const input = page.getByTestId('video-title-en')
  await input.fill('Intuitive layout')
  await page.screenshot({ path: testInfo.outputPath('workspace-layout.png') })
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  const save = page.getByTestId('snapshot-save')
  await expect(save).toBeInViewport()
  await expect(page.getByTestId('studio-preview')).toBeInViewport()
  const header = page.locator('.studio-topbar')
  await expect.poll(async () => (await header.boundingBox())!.y).toBe(0)
  await input.focus()
  await input.evaluate(element => element.scrollIntoView({ block: 'start' }))
  const bounds = (await input.boundingBox())!
  const top = (await header.boundingBox())!
  expect(bounds.y).toBeGreaterThanOrEqual(top.y + top.height)
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  await page.keyboard.press('Shift+Tab')
  await expect(page.locator('[data-testid="video-fields"] .localized-english summary').first()).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByTestId('video-title-zh')).toBeFocused()
  const keyboardBounds = (await page.getByTestId('video-title-zh').boundingBox())!
  expect(keyboardBounds.y).toBeGreaterThanOrEqual((await header.boundingBox())!.height)
  expect(keyboardBounds.y + keyboardBounds.height).toBeLessThanOrEqual(page.viewportSize()!.height)
  await save.click()
  await expect(page.locator('.studio-meta')).toContainText('Saved')
  await page.screenshot({ path: testInfo.outputPath('editing-layout.png'), fullPage: true })
})

test('极窄短屏长版本名和导航分组仍可操作且没有横向溢出', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 320, height: 420 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const api = await backend(page)
  api.records.get('ver_14cea400-a42f-4560-9770-3de88cae9d5a')!.name = 'LongUnbrokenVersionName'.repeat(5)
  await page.addInitScript(() => localStorage.setItem('yujian:admin-locale', 'en'))
  await page.goto('/')
  await expect(page.getByTestId('studio-version-name')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Submit review', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.locator('.studio-menu').click()
  await expect(page.getByRole('navigation', { name: 'Content studio' }).filter({ visible: true }).locator('.studio-nav-group')).toHaveCount(3)
  const logout = page.getByTestId('studio-logout').filter({ visible: true })
  await logout.scrollIntoViewIfNeeded()
  await expect(logout).toBeInViewport()
  await page.keyboard.press('Escape')
  await selectVersion(page, 'ver_8bb3a437-061d-4dcd-805e-7d5e6f716921')
  await expect(page.getByRole('button', { name: 'Rollback', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('narrow-version-layout.png'), fullPage: true })
})

test('任意编辑模块的审核发布目标跟随版本，未保存内容阻止提交', async ({ page }) => {
  const api = await startStudio(page)
  await navigate(page, 'video')
  const submit = page.getByRole('button', { name: 'Submit review', exact: true })
  await expect(submit).toBeEnabled()
  await page.getByTestId('video-title-en').fill('Unsaved input')
  await expect(submit).toBeDisabled()
  await page.getByTestId('snapshot-save').click()
  await expect(submit).toBeEnabled()
  let submitted = false
  await page.route('**/api/v1/versions/ver_14cea400-a42f-4560-9770-3de88cae9d5a/review', route => {
    submitted = true
    expect(route.request().postDataJSON()).toEqual({ revision: 5 })
    const record = api.records.get('ver_14cea400-a42f-4560-9770-3de88cae9d5a')!
    Object.assign(record, { status: 'in_review', revision: 6 })
    return route.fulfill({ json: record })
  })
  await submit.click()
  await expect(page.locator('.studio-meta')).toContainText('In review')
  expect(submitted).toBe(true)
  await page.getByRole('button', { name: 'Approve / Return to draft', exact: true }).click()
  await expect(page.locator('.studio-dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('heading', { name: 'Review version' })).toBeVisible()
  await page.getByTestId('dialog-close').click()
  await selectVersion(page, 'ver_8bb3a437-061d-4dcd-805e-7d5e6f716921')
  await expect(page.getByRole('button', { name: 'Approve / Return to draft', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Rollback', exact: true })).toBeEnabled()
  expect(await page.locator('[data-module]').getAttribute('data-module')).toBe('video')
})
