import { expect, test } from '@playwright/test'
import fixture from '../../../../content/fixtures/homepage.json' with { type: 'json' }
import { apply, navigate, roundTrip, snapshot, startStudio } from './studio'

test('新增片段、首页引用、真实预览与导出再导入', async ({ page }) => {
  await startStudio(page)
  await navigate(page, 'moment')
  await page.getByTestId('moment-add').click()
  await expect(page.getByTestId('moment-caption-zh')).toHaveCount(0)
  await page.getByTestId('moment-asset').selectOption('asset_cover_01')
  await page.getByTestId('moment-custom-caption').check()
  await page.getByTestId('moment-caption-zh').fill('浏览器片段')
  await page.getByTestId('moment-caption-en').fill('Browser moment')
  await page.getByTestId('moment-target-kind').selectOption('internal')
  await page.getByTestId('moment-target-content').selectOption('release_01')
  await apply(page)
  const applied = await snapshot(page)
  const moment = applied.moments.at(-1)!
  expect(moment).toMatchObject({ assetId: 'asset_cover_01', caption: { 'zh-CN': '浏览器片段', en: 'Browser moment' }, target: { kind: 'internal', contentId: 'release_01' } })
  expect(applied.homepage).toEqual(fixture.homepage)
  await navigate(page, 'homepage')
  const section = page.getByTestId('homepage-section-section_moment')
  await section.getByTestId('homepage-item-add-select').selectOption(moment.id)
  await section.getByTestId('homepage-item-add').click()
  await section.getByTestId('homepage-section-limit').fill('4')
  await page.getByTestId('studio-preview').click()
  const figure = page.getByTestId('preview-frame').contentFrame().locator(`figure#${moment.id}`)
  await expect(figure).toBeVisible()
  await expect(figure.locator('a')).toHaveAttribute('href', '#release_01')
  await expect(figure.getByRole('img')).toHaveAccessibleName(fixture.assets.find(asset => asset.id === 'asset_cover_01')!.alt.en)
  await page.getByTestId('dialog-close').click()
  await roundTrip(page, await snapshot(page))
})

test('内部目标与外链安全预览，可选 caption 和 label 删除', async ({ page }) => {
  await startStudio(page)
  await navigate(page, 'moment')
  const figure = page.getByTestId('preview-frame').contentFrame().locator('#moment_01')
  await page.getByTestId('moment-target-kind').selectOption('internal')
  await page.getByTestId('moment-target-content').selectOption('release_01')
  await page.getByTestId('studio-preview').click()
  await expect(figure.locator('a')).toHaveAttribute('href', '#release_01')
  await figure.locator('a').click()
  await expect(page.getByTestId('preview-frame').contentFrame().locator('#release_01')).toBeInViewport()
  await page.getByTestId('dialog-close').click()
  await page.getByTestId('moment-target-kind').selectOption('external')
  await page.getByTestId('moment-target-provider').selectOption('bilibili')
  await page.getByTestId('moment-target-url').fill('https://example.com/moment')
  await page.getByTestId('moment-target-custom-label').check()
  await page.getByTestId('moment-target-label-zh').fill('片段链接')
  await page.getByTestId('moment-target-label-en').fill('Moment link')
  await page.getByTestId('moment-target-label-en').fill('')
  await page.getByTestId('moment-caption-en').fill('')
  await page.getByTestId('studio-preview').click()
  await expect(figure.locator('a')).toHaveAttribute('href', 'https://example.com/moment')
  await expect(figure.locator('a')).toHaveAttribute('target', '_blank')
  await expect(figure.locator('a')).toHaveAttribute('rel', 'noopener noreferrer')
  const before = page.url()
  const pagesBefore = page.context().pages().length
  await figure.locator('a').click()
  expect(page.url()).toBe(before)
  expect(page.context().pages()).toHaveLength(pagesBefore)
  await page.getByTestId('dialog-close').click()
  expect((await snapshot(page)).moments[0]!.caption).not.toHaveProperty('en')
  await page.getByTestId('moment-target-custom-label').uncheck()
  await page.getByTestId('moment-custom-caption').uncheck()
  await apply(page)
  const value = (await snapshot(page)).moments[0]!
  expect(value).not.toHaveProperty('caption')
  expect(value.target).toEqual({ kind: 'external', link: { provider: 'bilibili', url: 'https://example.com/moment' } })
  await page.getByTestId('moment-target-kind').selectOption('none')
  await page.getByTestId('studio-preview').click()
  await expect(figure.locator('a')).toHaveCount(0)
  await page.getByTestId('dialog-close').click()
  expect((await snapshot(page)).moments[0]).not.toHaveProperty('target')
})

test('片段离开保护与缺失素材拒绝保存', async ({ page }) => {
  const api = await startStudio(page)
  await navigate(page, 'moment')
  await page.getByTestId('moment-caption-en').fill('Keep moment')
  await navigate(page, 'event')
  await page.getByTestId('leave-keep').focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('moment-caption-en')).toHaveValue('Keep moment')
  await page.getByTestId('moment-asset').selectOption('')
  await page.getByTestId('snapshot-save').click()
  await expect(page.getByTestId('toast-viewport')).toContainText('/moments/0/assetId')
  await expect(page.getByTestId('moment-error')).toHaveCount(0)
  expect(api.saves).toHaveLength(0)
  await page.locator('.rail-locale').filter({ visible: true }).click()
  await expect(page.getByTestId('moment-caption-en')).toHaveValue('Keep moment')
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await navigate(page, 'event')
  await page.getByTestId('leave-discard').click()
  await navigate(page, 'moment')
  await expect(page.getByTestId('moment-caption-en')).toHaveValue(fixture.moments[0]!.caption!.en)
})

test('保存契约：409 保留、保存锁定、成功刷新片段基线', async ({ page }) => {
  const api = await startStudio(page)
  await navigate(page, 'moment')
  api.conflict = true
  await page.getByTestId('moment-caption-en').fill('Saved moment')
  await page.getByTestId('snapshot-save').click()
  await expect(page.getByTestId('toast-viewport')).toContainText('req_browser')
  expect((await snapshot(page)).moments[0]!.caption!.en).toBe('Saved moment')
  await page.getByTestId('moment-caption-en').fill('Retry moment')
  api.conflict = false
  api.hold = true
  await page.getByTestId('snapshot-save').click()
  for (const id of ['moment-caption-zh', 'moment-add', 'version-clone', 'studio-tools']) await expect(page.getByTestId(id)).toBeDisabled()
  await expect.poll(() => Boolean(api.finish)).toBe(true)
  api.finish!()
  await expect(page.getByTestId('moment-caption-en')).toHaveValue('Retry moment')
  await expect(page.getByTestId('moment-caption-en')).toBeEnabled()
  await expect(page.locator('.studio-meta')).toContainText('Saved')
})
