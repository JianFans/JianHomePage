test('保存契约：409 保留、保存锁定、成功刷新全部已打开基线', async ({ page, baseURL }) => {
  await page.getByLabel('API base URL').fill(`${baseURL}/backend`)
  await page.locator('.connection-grid input[type="text"]').fill('ver_moment')
  let fail = true
  let finish: (() => void) | undefined
  await page.route('**/backend/api/v1/versions/ver_moment', async (route) => {
    let value = fixture
    let revision = 4
    if (route.request().method() === 'PUT') {
      expect(route.request().headers()['if-match']).toBe('"4"')
      if (fail) return route.fulfill({ status: 409, json: { code: 'revision_conflict', message: 'Revision conflict', requestId: 'req_moment' } })
      value = route.request().postDataJSON().snapshot
      revision = 5
      await new Promise<void>((resolve) => { finish = resolve })
    }
    await route.fulfill({ json: { id: 'ver_moment', status: 'draft', revision, snapshot: value, checksum: 'sha256:contract' } })
  })
  await page.getByTestId('version-load').click()
  await expect(page.getByTestId('snapshot-validation')).toHaveText('Valid')
  await page.getByTestId('moment-open').click()
  await page.getByTestId('event-open').click()
  await page.getByTestId('video-open').click()
  await page.getByTestId('homepage-open').click()
  await page.getByTestId('music-release-release_01').click()
  await page.getByTestId('moment-caption-en').fill('Saved moment')
  await page.getByTestId('moment-apply').click()
  await page.getByTestId('snapshot-save').click()
  await expect(page.locator('.notice--error')).toContainText('req_moment')
  expect((await snapshot(page)).moments[0]!.caption!.en).toBe('Saved moment')
  await page.getByTestId('moment-caption-en').fill('Retry moment')
  await expect(page.getByTestId('moment-apply')).toBeEnabled()
  await page.getByTestId('moment-apply').click()
  fail = false
  await page.getByTestId('snapshot-save').click()
  for (const id of ['event-title-zh', 'event-add', 'event-open', 'moment-caption-zh', 'moment-add', 'moment-open', 'version-load', 'homepage-open', 'music-new', 'video-open', 'video-add']) await expect(page.getByTestId(id)).toBeDisabled()
  await expect.poll(() => Boolean(finish)).toBe(true)
  finish!()
  await expect(page.getByTestId('snapshot-unsaved')).toHaveCount(0)
  await page.getByTestId('moment-caption-en').fill('Next moment')
  await page.getByTestId('homepage-headline-en').fill('Next homepage')
  await page.getByTestId('release-title-en').fill('Next music')
  await page.getByTestId('event-title-en').fill('Next event')
  await page.getByTestId('video-title-en').fill('Next video')
  for (const id of ['moment-apply', 'homepage-apply', 'music-apply', 'video-apply', 'event-apply']) await expect(page.getByTestId(id)).toBeEnabled()
})
