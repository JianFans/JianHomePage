test('模块导航每次只显示目标工作台，抽屉与键盘符合窄屏布局', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await startStudio(page)
  const active = page.locator('[data-module], [data-testid="asset-workbench"]').filter({ visible: true })
  for (const module of ['homepage', 'music', 'video', 'event', 'moment', 'assets', 'history'] as Module[]) {
    await navigate(page, module)
    if (module === 'assets') await expect(page.getByTestId('asset-workbench')).toBeVisible()
    else await expect(active).toHaveAttribute('data-module', module)
    await expect(active).toHaveCount(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    expect(await active.evaluate(element => getComputedStyle(element).transitionDuration)).toBe('0s')
  }
  await page.getByTestId('studio-tools').focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(page.locator('.studio-dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByTestId('studio-tools')).toBeFocused()
  await navigate(page, 'homepage')
  await page.screenshot({ path: testInfo.outputPath('studio-homepage.png'), fullPage: true })
})

