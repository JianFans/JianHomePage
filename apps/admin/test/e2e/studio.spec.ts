test('素材上传进行中不能注销，失败后保留输入并恢复退出入口', async ({ page }) => {
  const api = await startStudio(page)
  let finish: (() => void) | undefined
  await page.route('**/api/v1/assets/uploads', async (route) => {
    expect(route.request().headers()['x-csrf-token']).toBe(csrfToken)
    expect(route.request().postDataJSON()).toMatchObject({ fileName: 'pending-cover.webp', contentType: 'image/webp', rights: { source: { 'zh-CN': '上传来源' } } })
    await new Promise<void>((resolve) => { finish = resolve })
    await route.fulfill({ status: 500, json: { code: 'upload_failed', message: 'Upload unavailable', requestId: 'req_6de4a79d-08da-4800-892e-7664cd33aad1' } })
  })
  await navigate(page, 'assets')
  await page.getByTestId('asset-file-input').setInputFiles({ name: 'pending-cover.webp', mimeType: 'image/webp', buffer: Buffer.from('pending-file-selection') })
  await page.getByTestId('asset-source-zh').fill('上传来源')
  await page.getByTestId('asset-alt-upload-zh').fill('上传替代文本')
  await page.getByTestId('asset-upload').click()
  await expect.poll(() => Boolean(finish)).toBe(true)
  await expect(page.getByTestId('asset-stage')).toContainText('Creating upload')
  if (await page.locator('.studio-menu').isVisible()) await page.locator('.studio-menu').click()
  await expect(page.getByTestId('studio-logout').filter({ visible: true })).toBeDisabled()
  finish!()
  await expect(page.getByTestId('studio-logout').filter({ visible: true })).toBeEnabled()
  if (await page.getByTestId('dialog-close').isVisible()) await page.getByTestId('dialog-close').click()
  await expect(page.getByTestId('asset-stage')).toContainText('Upload failed')
  await expect(page.getByTestId('asset-source-zh')).toHaveValue('上传来源')
  await expect(page.getByTestId('asset-alt-upload-zh')).toHaveValue('上传替代文本')
  expect(api.writes.some(request => request.url().endsWith('/auth/logout'))).toBe(false)
})

