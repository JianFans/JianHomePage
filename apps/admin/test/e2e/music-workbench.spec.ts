test('合法重复引用可编辑、排序并按引用移除，曲目记录保持唯一', async ({ page }) => {
  const value = fixtureSnapshot()
  value.releases[0]!.trackIds.push('track_e60c46c7-28d6-418e-8905-167307dc8354')
  value.homepage.sections.find(section => section.type === 'music')!.itemIds = ['release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff', 'release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff', 'release_f9462a63-70d9-40b3-a0cc-a792f1b5499e']
  await startStudio(page, value)
  await navigate(page, 'music')
  await page.getByTestId('music-release-release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff').click()
  const tracks = page.getByTestId('track-editor')
  await expect(tracks).toHaveCount(2)
  await tracks.nth(1).getByTestId('track-title-zh').fill('重复引用的曲目')
  await expect(tracks.nth(0).getByTestId('track-title-zh')).toHaveValue('重复引用的曲目')
  await page.getByTestId('track-add').click()
  await tracks.nth(2).getByTestId('track-title-zh').fill('中间曲目')
  await tracks.nth(2).getByTestId('track-duration').fill('180')
  await tracks.nth(2).getByTestId('track-up').click()
  await apply(page)
  const applied = await snapshot(page)
  const newId = applied.tracks.at(-1)!.id
  expect(applied.releases[0]!.trackIds).toEqual(['track_e60c46c7-28d6-418e-8905-167307dc8354', newId, 'track_e60c46c7-28d6-418e-8905-167307dc8354'])
  expect(applied.homepage).toEqual(value.homepage)
  expect(applied.tracks.filter(track => track.id === 'track_e60c46c7-28d6-418e-8905-167307dc8354')).toHaveLength(1)
  expect(applied.tracks[0]!.title['zh-CN']).toBe('重复引用的曲目')
  await tracks.nth(0).getByTestId('track-remove').click()
  await apply(page)
  const removed = await snapshot(page)
  expect(removed.releases[0]!.trackIds).toEqual([newId, 'track_e60c46c7-28d6-418e-8905-167307dc8354'])
  expect(removed.tracks.filter(track => track.id === 'track_e60c46c7-28d6-418e-8905-167307dc8354')).toHaveLength(1)
  await expect(tracks.nth(1).getByTestId('track-title-zh')).toHaveValue('重复引用的曲目')
  const placement = page.getByTestId('section-section_1941aa2b-341c-471c-9408-760fbd9edcea')
  await placement.getByTestId('section-down').click()
  await apply(page)
  expect((await snapshot(page)).homepage.sections.find(section => section.type === 'music')!.itemIds).toEqual(['release_f9462a63-70d9-40b3-a0cc-a792f1b5499e', 'release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff', 'release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff'])
  await expect(placement.getByTestId('section-down')).toBeDisabled()
  await placement.getByTestId('section-up').click()
  await apply(page)
  expect((await snapshot(page)).homepage.sections.find(section => section.type === 'music')!.itemIds).toEqual(['release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff', 'release_f9462a63-70d9-40b3-a0cc-a792f1b5499e', 'release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff'])
  await expect(placement.getByTestId('section-up')).toBeDisabled()
})

