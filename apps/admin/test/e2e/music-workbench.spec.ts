test('保存 API 契约：修订冲突保留，忙碌锁定，快速成功保持最新表单', async ({ page }) => {
  const api = await startStudio(page)
  await navigate(page, 'music')
  await page.getByTestId('music-release-release_5081a10a-7f9a-4af5-a7dc-2b522e1d3cff').click()
  api.conflict = true
  await page.getByTestId('release-title-en').fill('Saved title')
  await page.getByTestId('snapshot-save').click()
  await expect(page.getByTestId('toast-viewport')).toContainText('req_c4464811-558f-4491-b698-2404d74f0167')
  expect((await snapshot(page)).releases[0]!.title.en).toBe('Saved title')
  api.conflict = false
  api.hold = true
  await page.getByTestId('snapshot-save').click()
  for (const id of ['release-title-zh', 'track-add', 'version-clone', 'studio-tools']) await expect(page.getByTestId(id)).toBeDisabled()
  await expect.poll(() => Boolean(api.finish)).toBe(true)
  api.finish!()
  await expect(page.getByTestId('release-title-en')).toBeEnabled()
  await expect(page.locator('.studio-meta')).toContainText('Saved')
  api.hold = false
  await page.getByTestId('release-title-en').fill('Fast saved title')
  await page.getByTestId('snapshot-save').click()
  await expect(page.locator('.studio-meta')).toContainText('Saved')
  await expect(page.getByTestId('release-title-en')).toHaveValue('Fast saved title')
  expect(api.saves.at(-1)!.releases[0]!.title.en).toBe('Fast saved title')
})

