type requestLogKey struct{}

type requestLog struct {
	logger             *slog.Logger
	route              string
	failed             bool
	generatedByLogging bool
	fields             []any
}

var safeResourceID = regexp.MustCompile(`^(?:ver|asset|pub|build)_[A-Za-z0-9_-]{1,128}$`)

// LoggingMiddleware emits one structured event per request without recording
// headers or bodies. The request ID is generated by the outer middleware and
// the actor subject is read from the private authentication context.
func LoggingMiddleware(next http.Handler, logger *slog.Logger) http.Handler {
	if logger == nil {
		logger = slog.Default()
	}
	return http.HandlerFunc(func(writer http.ResponseWriter, request *http.Request) {
		id := strings.TrimSpace(request.Header.Get("X-Request-ID"))
		generatedByLogging := !validExternalRequestID(id)
		if generatedByLogging {
			id = fmt.Sprintf("req-%s", rand.Text())
		}
		request.Header.Set("X-Request-ID", id)
		writer.Header().Set("X-Request-ID", id)
		state := &requestLog{logger: logger, generatedByLogging: generatedByLogging}
		ctx := observability.WithLogger(request.Context(), logger.With("request_id", id))
		*request = *request.WithContext(context.WithValue(ctx, requestLogKey{}, state))
		started := time.Now()
		response := &statusWriter{ResponseWriter: writer}
		defer func() {
			actorSubject := ""
			if principal, ok := auth.PrincipalFromContext(request.Context()); ok {
				actorSubject = principal.Subject
			}
			route := safeRequestRoute(request, state.route)
			level := requestLevel(response.statusCode())
			if response.statusCode() < 400 && (request.URL.Path == "/healthz" || isStaticRoute(request.URL.Path)) {
				level = slog.LevelDebug
			}
			fields := []any{
				"component", "http", "method", request.Method,
				"request_id", request.Header.Get("X-Request-ID"),
				"actor_subject", actorSubject,
				"route", route,
				"status", response.statusCode(),
				"response_bytes", response.bytes,
				"duration_ms", time.Since(started).Milliseconds(),
			}
			fields = append(fields, state.fields...)
			logger.Log(request.Context(), level, "http request", fields...)
		}()
		// Recovery runs first; the independent request defer still runs if it re-panics.
		defer func() {
			if recovered := recover(); recovered != nil {
				if recovered == http.ErrAbortHandler {
					panic(recovered)
				}
				stack := make([]byte, 16*1024)
				stack = stack[:runtime.Stack(stack, false)]
				// Panic values may contain request bodies or credentials. The code stack identifies the fault.
				observability.Logger(request.Context()).ErrorContext(request.Context(), "http handler panicked", "component", "http", "panic_type", fmt.Sprintf("%T", recovered), "stack", string(stack), "response_committed", response.wroteHeader)
				if response.wroteHeader {
					panic(http.ErrAbortHandler)
				}
				writeError(response, request, 500, "internal_error", "Service unavailable.")
			}
		}()
		next.ServeHTTP(response, request)
	})
}

// safeRequestRoute keeps matched templates while replacing arbitrary paths with fixed categories.
func safeRequestRoute(request *http.Request, matched string) string {
	if matched != "" {
		return matched
	}
	if request.Pattern != "" {
		return request.Pattern
	}
	path := request.URL.Path
	switch path {
	case "/healthz", "/api/v1/auth/session", "/api/v1/auth/login", "/api/v1/auth/callback", "/api/v1/auth/logout":
		return path
	}
	for _, prefix := range []string{"/_nuxt/", "/site/", "/local-upload/", "/media/"} {
		if strings.HasPrefix(path, prefix) {
			return prefix + "{asset}"
		}
	}
	return "unmatched"
}

// isStaticRoute identifies compiled browser resources whose successful requests
// are debug noise; uploaded media and API traffic retain normal request levels.
func isStaticRoute(path string) bool {
	return strings.HasPrefix(path, "/_nuxt/") || strings.HasPrefix(path, "/site/")
}

// validRequestID bounds trusted identifiers while rejecting control characters and log injection.
func validRequestID(id string) bool {
	if id == "" || len(id) > 128 {
		return false
	}
	for _, r := range id {
		if r < 33 || r > 126 {
			return false
		}
	}
	return true
}

// validExternalRequestID only accepts UUIDs as caller-supplied request IDs.
func validExternalRequestID(id string) bool {
	if len(id) != 36 {
		return false
	}
	for index := range id {
		if index == 8 || index == 13 || index == 18 || index == 23 {
			if id[index] != '-' {
				return false
			}
			continue
		}
		value := id[index]
		if !((value >= '0' && value <= '9') || (value >= 'a' && value <= 'f') || (value >= 'A' && value <= 'F')) {
			return false
		}
	}
	return true
}

// requestLevel distinguishes rejected input from service faults and successful operations.
func requestLevel(status int) slog.Level {
	if status >= 500 {
		return slog.LevelError
	}
	if status >= 400 {
		return slog.LevelWarn
	}
	return slog.LevelInfo
}

// routeHandler retains the matched template and resource identifiers across ServeMux request copies.
func routeHandler(endpoint http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if state, ok := r.Context().Value(requestLogKey{}).(*requestLog); ok {
			state.route = r.Pattern
			state.fields = resourceFields(r)
		}
		endpoint(w, r)
	}
}

// resourceFields extracts path identities without copying queries, payloads or signed URLs.
func resourceFields(r *http.Request) []any {
	var fields []any
	for _, pair := range [][2]string{{"versionId", "version_id"}, {"assetId", "asset_id"}, {"publishId", "job_id"}, {"buildId", "build_id"}} {
		if id := r.PathValue(pair[0]); safeResourceID.MatchString(id) {
			fields = append(fields, pair[1], id)
		}
	}
	return fields
}

// logOperation records an original error before the public response deliberately hides its cause.
func logOperation(r *http.Request, err error, status int, code, message string, fields ...any) {
	if state, ok := r.Context().Value(requestLogKey{}).(*requestLog); ok {
		state.failed = true
	}
	actor, _ := auth.PrincipalFromContext(r.Context())
	attrs := []any{"component", "management", "method", r.Method, "route", r.Pattern, "actor_subject", actor.Subject, "status", status, "error_kind", code}
	if _, hasRequestLogger := r.Context().Value(requestLogKey{}).(*requestLog); !hasRequestLogger {
		attrs = append(attrs, "request_id", r.Header.Get("X-Request-ID"))
	}
	attrs = append(attrs, resourceFields(r)...)
	attrs = append(attrs, fields...)
	if err != nil && (status >= http.StatusInternalServerError || !expectedDomainRejection(err)) {
		attrs = append(attrs, observability.Error(err))
	}
	observability.Logger(r.Context()).Log(r.Context(), requestLevel(status), message, attrs...)
}

// expectedDomainRejection identifies business rejections whose wrapped details
// may contain caller data and must therefore be omitted from operation logs.
func expectedDomainRejection(err error) bool {
	return errors.Is(err, domain.ErrForbidden) || errors.Is(err, domain.ErrNotFound) || errors.Is(err, domain.ErrConflict) ||
		errors.Is(err, domain.ErrInvalidInput) || errors.Is(err, domain.ErrInvalidTransition) || errors.Is(err, domain.ErrDuplicateRequest)
}

type statusWriter struct {
	http.ResponseWriter
	wroteHeader bool
	status      int
	bytes       int64
}

// Unwrap preserves ResponseController capabilities through the logging wrapper.
func (writer *statusWriter) Unwrap() http.ResponseWriter {
	return writer.ResponseWriter
}

// WriteHeader records and forwards only the first status, keeping request logs
// consistent with the response already committed to the underlying connection.
func (writer *statusWriter) WriteHeader(status int) {
	if writer.wroteHeader {
		return
	}
	if status >= 100 && status < 200 && status != http.StatusSwitchingProtocols {
		writer.ResponseWriter.WriteHeader(status)
		return
	}
	writer.wroteHeader = true
	writer.status = status
	writer.ResponseWriter.WriteHeader(status)
}

// Write captures implicit HTTP 200 responses and counts bytes actually accepted
// by the underlying writer, including partial writes that return an error.
func (writer *statusWriter) Write(value []byte) (int, error) {
	if !writer.wroteHeader {
		writer.WriteHeader(http.StatusOK)
	}
	n, err := writer.ResponseWriter.Write(value)
	writer.bytes += int64(n)
	return n, err
}

func (writer *statusWriter) statusCode() int {
	if writer.status == 0 {
		return http.StatusOK
	}
	return writer.status
}
