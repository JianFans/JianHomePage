import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repository = fileURLToPath(new URL('../', import.meta.url))
const manifests = ['package.json', 'apps/web/package.json', 'apps/admin/package.json', 'packages/schema/package.json']
const goVersionFile = 'apps/server/cmd/api/version.go'

/** Accept only canonical stable release versions, including exact end-of-input. */
export function isReleaseVersion(version) {
  return typeof version === 'string' && /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.exec(version)?.[0] === version
}

/** Read every release file before writing so missing or inconsistent versions fail closed. */
function readFiles(root) {
  const packages = manifests.map(path => ({ path, data: JSON.parse(readFileSync(join(root, path), 'utf8')) }))
  const goSource = readFileSync(join(root, goVersionFile), 'utf8')
  const goVersion = /^const Version = "([^"]+)"\r?$/m.exec(goSource)?.[1]
  const versions = [...packages.map(pkg => pkg.data.version), goVersion]
  if (!versions.every(isReleaseVersion)) throw new Error('发布文件缺少合法的稳定版本')
  if (!versions.every(version => version === versions[0])) throw new Error('Node 与 Go 的发布版本不一致')
  return { packages, version: versions[0] }
}

/** Return the common application version; Go toolchain and content schema versions are independent. */
export function readReleaseVersion(root = repository) {
  return readFiles(root).version
}

/** Synchronize Node manifests and the dedicated Go version constant after validating all inputs. */
export function setReleaseVersion(version, root = repository) {
  if (!isReleaseVersion(version)) throw new Error('发布版本必须为 X.Y.Z 格式的稳定版本')
  const { packages } = readFiles(root)
  for (const { path, data } of packages) {
    writeFileSync(join(root, path), `${JSON.stringify({ ...data, version }, null, 2)}\n`)
  }
  writeFileSync(join(root, goVersionFile), `// Code generated by scripts/set-release-version.mjs; DO NOT EDIT.\npackage main\n\n// Version identifies the application release, independently of the Go toolchain.\nconst Version = "${version}"\n`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [argument, expected, ...extra] = process.argv.slice(2)
  if (extra.length || (argument !== '--check' && expected !== undefined)) throw new Error('用法：set-release-version.mjs X.Y.Z | --check [X.Y.Z]')
  if (argument === '--check') {
    const actual = readReleaseVersion()
    if (expected && actual !== expected) throw new Error(`文件版本 ${actual} 与发布版本 ${expected} 不一致`)
    console.log(actual)
  } else {
    setReleaseVersion(argument)
  }
}
